// Generic .env variable names. Per-port vars derive from the port name via
// EnvVarForPort (e.g. `app` -> `APP_PORT`); every other key (including
// BASE_URL-style app URLs) is user-owned and inherited verbatim from the
// seed .env.
const (
	EnvApp = "APP_PORT"
	// EnvAppURL is the gateway URL for a worktree
	// (http://<slug>.<domain>[:port]); injected into runner env when
	// proxy.enabled, never written into the worktree .env.
	EnvAppURL = "APP_URL"
)

// EnvFileName is the generated file name inside each worktree.
const EnvFileName = ".env"

// EnvVarForPort maps a port name to its .env variable (e.g. `app` ->
// `APP_PORT`, `web` -> `WEB_PORT`). Non-alphanumeric runs become a single
// underscore so names like `api-v2` stay valid shell identifiers.
func EnvVarForPort(name string) string {
	var b strings.Builder
	prevUnderscore := true // leading trim: avoid a leading underscore
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(unicode.ToUpper(r))
			prevUnderscore = false
		} else if !prevUnderscore {
			b.WriteByte('_')
			prevUnderscore = true
		}
	}
	s := strings.Trim(b.String(), "_")
	if s == "" {
		return "PORT"
	}
	return s + "_PORT"
}

// AppURL builds http://<slug>.<domain>[:port] for a worktree gateway.
// Port 80 is omitted; empty domain defaults to localhost.
func AppURL(slug, domain string, gatewayPort int) string {
	d := strings.ToLower(strings.Trim(strings.TrimSpace(domain), "."))
	if d == "" {
		d = "localhost"
	}
	s := strings.ToLower(strings.TrimSpace(slug))
	if gatewayPort == 80 {
		return "http://" + s + "." + d
	}
	if gatewayPort <= 0 || gatewayPort > 65535 {
		return "http://" + s + "." + d
	}
	return "http://" + s + "." + d + ":" + fmt.Sprintf("%d", gatewayPort)
}

// ManagedValues maps every wrk3-managed .env variable to its value for
// the given allocation: one <NAME>_PORT per ports.base entry. Nothing else
// is managed: app-level URLs such as BASE_URL stay user-owned and are
// inherited verbatim from the seed .env.
func ManagedValues(ports map[string]int) (map[string]string, error) {
	if len(ports) == 0 {
		return map[string]string{}, nil
	}
	out := make(map[string]string, len(ports))
	for name, v := range ports {
		out[EnvVarForPort(name)] = fmt.Sprintf("%d", v)
	}
	return out, nil
}

// RewriteURL replaces the port in baseURL with port, preserving scheme,
// host, and path. baseURL must have an explicit port.
func RewriteURL(baseURL *url.URL, port int) string {
	host := baseURL.Hostname()
	p := strconv.Itoa(port)
	urlStr := baseURL.Scheme + "://" + host + ":" + p + baseURL.Path
	if baseURL.RawQuery != "" {
		urlStr += "?" + baseURL.RawQuery
	}
	if baseURL.Fragment != "" {
		urlStr += "#" + baseURL.Fragment
	}
	return urlStr
}

// URLValues maps configured URL vars to their rewritten URL values.
// Each var gets the rewritten URL with its allocated port.
func URLValues(urlPorts map[string]int, specs []URLSpec) map[string]string {
	if len(urlPorts) == 0 || len(specs) == 0 {
		return nil
	}
	specByVar := make(map[string]URLSpec, len(specs))
	for _, s := range specs {
		specByVar[s.Var] = s
	}
	out := make(map[string]string, len(urlPorts))
	for v, port := range urlPorts {
		s, ok := specByVar[v]
		if !ok {
			continue
		}
		out[v] = RewriteURL(s.BaseURL, port)
	}
	return out
}

// desiredEnv builds the combined desired map from port and URL allocations.
func desiredEnv(ports map[string]int, urlPorts map[string]int, specs []URLSpec) (map[string]string, error) {
	desired, err := ManagedValues(ports)
	if err != nil {
		return nil, err
	}
	for k, v := range URLValues(urlPorts, specs) {
		desired[k] = v
	}
	return desired, nil
}

// managedHeader marks the appended block in pre-existing .env files.
const managedHeader = "# Managed by wrk3 — port allocations (other lines preserved)."

// generatedHeader is written only for fresh .env files. Pre-existing files
// keep their own unmanaged content; missing managed keys are appended under
// managedHeader and existing managed keys are rewritten to the allocation.
const generatedHeader = "# Generated by wrk3 — do not edit."

// parseKey extracts the variable name from a .env assignment line.
// It reports ok=false for blank lines, comments, and non-assignments.
// It tolerates `export KEY=...`, surrounding whitespace, and `KEY = ...`.
func parseKey(line string) (key string, ok bool) {
	trimmed := strings.TrimSpace(strings.TrimSuffix(line, "\r"))
	if trimmed == "" || strings.HasPrefix(trimmed, "#") {
		return "", false
	}
	rest := trimmed
	if strings.HasPrefix(rest, "export") && len(rest) > len("export") &&
		(rest[len("export")] == ' ' || rest[len("export")] == '\t') {
		rest = strings.TrimSpace(rest[len("export"):])
	}
	idx := strings.Index(rest, "=")
	if idx < 0 {
		return "", false
	}
	key = strings.TrimSpace(rest[:idx])
	if key == "" {
		return "", false
	}
	for i, r := range key {
		if r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			if i == 0 && unicode.IsDigit(r) {
				return "", false
			}
			continue
		}
		return "", false
	}
	return key, true
}

// splitComment splits a post-= value into value and trailing comment.
// Only ` <space>#` starts a comment so URLs and quoted `#` survive.
func splitComment(after string) (before, comment string) {
	for i := 0; i < len(after); i++ {
		if after[i] == '#' && i > 0 && (after[i-1] == ' ' || after[i-1] == '\t') {
			return strings.TrimRight(after[:i], " \t"), after[i:]
		}
	}
	return after, ""
}

// normValue normalizes a raw post-= value for comparison: it strips any
// trailing ` # comment`, surrounding whitespace, and one layer of matching
// single or double quotes. `APP_PORT="8000" # old` thus equals `8000`.
func normValue(after string) string {
	v, _ := splitComment(after)
	v = strings.TrimSpace(v)
	if len(v) >= 2 {
		if (v[0] == '"' && v[len(v)-1] == '"') || (v[0] == '\'' && v[len(v)-1] == '\'') {
			v = v[1 : len(v)-1]
		}
	}
	return v
}

// assignmentValue returns the normalized value of key's first assignment in
// line, or ok=false when line does not assign key. It tolerates
// `export KEY=...` and surrounding whitespace like parseKey.
func assignmentValue(line, key string) (value string, ok bool) {
	trimmed := strings.TrimSpace(strings.TrimSuffix(line, "\r"))
	if trimmed == "" || strings.HasPrefix(trimmed, "#") {
		return "", false
	}
	rest := trimmed
	if strings.HasPrefix(rest, "export") && len(rest) > len("export") &&
		(rest[len("export")] == ' ' || rest[len("export")] == '\t') {
		rest = strings.TrimSpace(rest[len("export"):])
	}
	idx := strings.Index(rest, "=")
	if idx < 0 {
		return "", false
	}
	if strings.TrimSpace(rest[:idx]) != key {
		return "", false
	}
	return normValue(rest[idx+1:]), true
}

// rewriteAssignmentLine sets key's value to want on line, preserving
// leading whitespace, an export prefix, key spacing, and a trailing
// comment. changed is false when line does not assign key or already
// holds want.
func rewriteAssignmentLine(line, key, want string) (out string, changed bool) {
	got, ok := assignmentValue(line, key)
	if !ok || got == want {
		return line, false
	}
	leadingLen := len(line) - len(strings.TrimLeft(line, " \t"))
	leading := line[:leadingLen]
	rest := strings.TrimSpace(line)
	prefix := ""
	if strings.HasPrefix(rest, "export") && len(rest) > len("export") &&
		(rest[len("export")] == ' ' || rest[len("export")] == '\t') {
		after := rest[len("export"):]
		wsLen := len(after) - len(strings.TrimLeft(after, " \t"))
		prefix = "export" + after[:wsLen]
		rest = strings.TrimSpace(after)
	}
	idx := strings.Index(rest, "=")
	if idx < 0 {
		return line, false
	}
	_, comment := splitComment(rest[idx+1:])
	out = leading + prefix + rest[:idx] + "=" + want
	if comment != "" {
		out += " " + comment
	}
	return out, true
}

// Render builds the .env file content for ports. Every entry in ports
// becomes <NAME>_PORT (sorted by port name for stable output).
func Render(ports map[string]int) (string, error) {
	return RenderFull(ports, nil, nil)
}

// RenderFull builds the .env file content for ports and URL vars.
// Port entries become <NAME>_PORT (sorted by port name); URL vars
// become <VAR>=<rewritten URL> (sorted by var name).
func RenderFull(ports map[string]int, urlPorts map[string]int, specs []URLSpec) (string, error) {
	if len(ports) == 0 {
		return "", fmt.Errorf("render .env: no ports allocated")
	}
	names := make([]string, 0, len(ports))
	for name := range ports {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(generatedHeader + "\n")
	for _, name := range names {
		fmt.Fprintf(&b, "%s=%d\n", EnvVarForPort(name), ports[name])
	}
	urlVals := URLValues(urlPorts, specs)
	if len(urlVals) > 0 {
		urlNames := make([]string, 0, len(urlVals))
		for k := range urlVals {
			urlNames = append(urlNames, k)
		}
		sort.Strings(urlNames)
		for _, k := range urlNames {
			fmt.Fprintf(&b, "%s=%s\n", k, urlVals[k])
		}
	}
	return b.String(), nil
}

// fillMissing rewrites managed keys already present to the desired value
// on the existing assignment line (first assignment still wins) and
// appends keys that are absent under managedHeader. Comments, blanks, and
// unmanaged lines are preserved.
func fillMissing(content string, desired map[string]string) (out string, added []string, changed bool) {
	// Normalize CRLF to LF for processing; callers write back LF.
	crlf := strings.Contains(content, "\r\n")
	body := strings.ReplaceAll(content, "\r\n", "\n")
	lines := strings.Split(body, "\n")
	seen := make(map[string]struct{}, len(desired))
	for i, line := range lines {
		key, ok := parseKey(line)
		if !ok {
			continue
		}
		want, managed := desired[key]
		if !managed {
			continue
		}
		if _, already := seen[key]; already {
			continue
		}
		seen[key] = struct{}{}
		next, rewritten := rewriteAssignmentLine(line, key, want)
		if rewritten {
			lines[i] = next
			changed = true
		}
	}
	var missing []string
	for k := range desired {
		if _, ok := seen[k]; !ok {
			missing = append(missing, k)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		added = append([]string(nil), missing...)
		// Drop the trailing empty element from Split so we control newlines.
		if len(lines) > 0 && lines[len(lines)-1] == "" {
			lines = lines[:len(lines)-1]
		}
		if len(lines) > 0 && lines[len(lines)-1] != "" {
			lines = append(lines, "")
		}
		hasMarker := false
		for _, l := range lines {
			if strings.TrimSpace(l) == managedHeader {
				hasMarker = true
				break
			}
		}
		if !hasMarker {
			lines = append(lines, managedHeader)
		}
		for _, k := range missing {
			lines = append(lines, k+"="+desired[k])
		}
	}
	out = strings.Join(lines, "\n")
	if out != "" && !strings.HasSuffix(out, "\n") {
		out += "\n"
	}
	if crlf {
		out = strings.ReplaceAll(out, "\n", "\r\n")
	}
	return out, added, changed
}

// checkPorts validates an allocation for .env use.
func checkPorts(ports map[string]int) error {
	if len(ports) == 0 {
		return fmt.Errorf("render .env: no ports allocated")
	}
	return nil
}

// Ensure guarantees <worktreePath>/.env contains the wrk3-managed port
// section: missing files are created via Render, existing files have
// managed keys rewritten to the allocation (first assignment wins) and
// missing managed keys appended under managedHeader. Unmanaged lines are
// never modified or deleted. It returns the keys appended (rewrites of
// existing managed keys are not listed).
// When ports is empty this is a no-op (local runner with no ports).
func Ensure(worktreePath string, ports map[string]int) (added []string, err error) {
	return EnsureExt(worktreePath, ports, nil, nil)
}

// EnsureExt is like Ensure but also handles URL vars from urlPorts/specs.
// When ports is empty this is a no-op.
func EnsureExt(worktreePath string, ports map[string]int, urlPorts map[string]int, specs []URLSpec) (added []string, err error) {
	if worktreePath == "" {
		return nil, fmt.Errorf("write .env: empty worktree path")
	}
	if len(ports) == 0 {
		return nil, nil
	}
	if err := checkPorts(ports); err != nil {
		return nil, err
	}
	desired, err := desiredEnv(ports, urlPorts, specs)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(worktreePath, 0o755); err != nil {
		return nil, fmt.Errorf("create worktree dir %q: %w", worktreePath, err)
	}
	path := filepath.Join(worktreePath, EnvFileName)
	raw, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return nil, fmt.Errorf("read .env %q: %w", path, err)
	}
	if os.IsNotExist(err) {
		content, err := RenderFull(ports, urlPorts, specs)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("write .env %q: %w", path, err)
		}
		for k := range desired {
			added = append(added, k)
		}
		sort.Strings(added)
		return added, nil
	}
	content, added, changed := fillMissing(string(raw), desired)
	if len(added) > 0 || changed {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("write .env %q: %w", path, err)
		}
	}
	return added, nil
}

// keepUnmanaged returns the lines of .env content that are not wrk3-managed:
// wrk3 header markers and managed assignments are dropped, everything else
// (user keys, comments, blank lines) is preserved verbatim.
func keepUnmanaged(content string, desired map[string]string) []string {
	body := strings.ReplaceAll(content, "\r\n", "\n")
	lines := strings.Split(body, "\n")
	var kept []string
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == generatedHeader || trimmed == managedHeader {
			continue
		}
		if key, ok := parseKey(line); ok {
			if _, managed := desired[key]; managed {
				continue
			}
		}
		kept = append(kept, line)
	}
	return kept
}

// trimBlankEnds drops leading/trailing blank lines.
func trimBlankEnds(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

// EnsureInherited ensures <worktreePath>/.env like Ensure, except that when
// the worktree has no .env yet, non-managed lines are seeded from the .env at
// seedPath (typically the repo-root checkout) before missing managed keys are
// appended. Managed <NAME>_PORT keys are never inherited — the worktree
// always gets its own allocation — while every other key (including BASE_URL
// style URLs) is copied verbatim. A missing seed file behaves like Ensure,
// and an existing worktree .env is ensured (managed keys overwritten), never
// reseeded. A seedPath equal to the worktree .env is ignored (self-seed).
func EnsureInherited(worktreePath, seedPath string, ports map[string]int) (added []string, err error) {
	return EnsureInheritedExt(worktreePath, seedPath, ports, nil, nil)
}

// EnsureInheritedExt is like EnsureInherited but also handles URL vars.
// When ports is empty this is a no-op.
func EnsureInheritedExt(worktreePath, seedPath string, ports map[string]int, urlPorts map[string]int, specs []URLSpec) (added []string, err error) {
	if worktreePath == "" {
		return nil, fmt.Errorf("write .env: empty worktree path")
	}
	if len(ports) == 0 {
		return nil, nil
	}
	if err := checkPorts(ports); err != nil {
		return nil, err
	}
	desired, err := desiredEnv(ports, urlPorts, specs)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(worktreePath, 0o755); err != nil {
		return nil, fmt.Errorf("create worktree dir %q: %w", worktreePath, err)
	}
	path := filepath.Join(worktreePath, EnvFileName)
	if _, err := os.Stat(path); err == nil {
		return EnsureExt(worktreePath, ports, urlPorts, specs)
	} else if !os.IsNotExist(err) {
		return nil, fmt.Errorf("stat .env %q: %w", path, err)
	}
	seed := ""
	if seedPath != "" && seedPath != path {
		raw, err := os.ReadFile(seedPath)
		if err != nil && !os.IsNotExist(err) {
			return nil, fmt.Errorf("read seed .env %q: %w", seedPath, err)
		}
		if err == nil {
			if kept := trimBlankEnds(keepUnmanaged(string(raw), desired)); len(kept) > 0 {
				onlyBlank := true
				for _, l := range kept {
					if strings.TrimSpace(l) != "" {
						onlyBlank = false
						break
					}
				}
				if !onlyBlank {
					seed = strings.Join(kept, "\n")
				}
			}
		}
	}
	if strings.TrimSpace(seed) == "" {
		content, err := RenderFull(ports, urlPorts, specs)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return nil, fmt.Errorf("write .env %q: %w", path, err)
		}
		for k := range desired {
			added = append(added, k)
		}
		sort.Strings(added)
		return added, nil
	}
	content, added, _ := fillMissing(seed, desired)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return nil, fmt.Errorf("write .env %q: %w", path, err)
	}
	return added, nil
}

// ReadPorts recovers a port allocation from the .env at
// filepath.Join(worktreePath, EnvFileName): for every name in base it reads
// the <NAME>_PORT variable (first assignment wins, like fillMissing).
// It returns the recovered map and ok=false when any name is missing or
// holds no valid TCP port — callers then fall back to a fresh allocation
// instead of adopting a partial/diverged set.
func ReadPorts(worktreePath string, base map[string]int) (recovered map[string]int, ok bool) {
	if len(base) == 0 {
		return map[string]int{}, true
	}
	raw, err := os.ReadFile(filepath.Join(worktreePath, EnvFileName))
	if err != nil {
		return nil, false
	}
	out := make(map[string]int, len(base))
	for name := range base {
		key := EnvVarForPort(name)
		found := false
		for _, line := range strings.Split(string(raw), "\n") {
			v, match := assignmentValue(line, key)
			if !match {
				continue
			}
			n := 0
			for _, r := range v {
				if r < '0' || r > '9' {
					n = -1
					break
				}
				n = n*10 + int(r-'0')
			}
			if n <= 0 || n > 65535 {
				return nil, false
			}
			out[name] = n
			found = true
			break
		}
		if !found {
			return nil, false
		}
	}
	return out, true
}

// StripManaged removes wrk3-managed assignment lines (plus wrk3 header
// markers) from the .env at path, preserving user keys. If nothing but
// blank lines remains, the file is deleted. It returns true when the file
// was deleted. Missing files are a no-op returning false.
func StripManaged(path string, ports map[string]int) (bool, error) {
	return StripManagedExt(path, ports, nil, nil)
}

// StripManagedExt is like StripManaged but also strips managed URL vars.
// When ports is empty this is a no-op.
func StripManagedExt(path string, ports map[string]int, urlPorts map[string]int, specs []URLSpec) (bool, error) {
	if len(ports) == 0 {
		return false, nil
	}
	desired, err := desiredEnv(ports, urlPorts, specs)
	if err != nil {
		return false, err
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, fmt.Errorf("read .env %q: %w", path, err)
	}
	kept := trimBlankEnds(keepUnmanaged(string(raw), desired))
	onlyBlank := true
	for _, l := range kept {
		if strings.TrimSpace(l) != "" {
			onlyBlank = false
			break
		}
	}
	if len(kept) == 0 || onlyBlank {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return false, fmt.Errorf("remove .env %q: %w", path, err)
		}
		return true, nil
	}
	out := strings.Join(kept, "\n") + "\n"
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		return false, fmt.Errorf("write .env %q: %w", path, err)
	}
	return false, nil
}

// ReadURLs recovers URL port allocations from the .env at
// filepath.Join(worktreePath, EnvFileName): for every URLSpec it reads
// the <VAR> variable, parses its URL value, and extracts the port.
// Returns the recovered var→port map and ok=false when any var is missing,
// has no URL with an explicit port, or the port is outside its configured
// range.
func ReadURLs(worktreePath string, specs []URLSpec) (recovered map[string]int, ok bool) {
	if len(specs) == 0 {
		return nil, true
	}
	raw, err := os.ReadFile(filepath.Join(worktreePath, EnvFileName))
	if err != nil {
		return nil, false
	}
	out := make(map[string]int, len(specs))
	for _, spec := range specs {
		found := false
		for _, line := range strings.Split(string(raw), "\n") {
			v, match := assignmentValue(line, spec.Var)
			if !match {
				continue
			}
			u, err := url.Parse(v)
			if err != nil {
				return nil, false
			}
			p := u.Port()
			if p == "" {
				return nil, false
			}
			n, err := strconv.Atoi(p)
			if err != nil || n <= 0 || n > 65535 {
				return nil, false
			}
			if n < spec.Range[0] || n > spec.Range[1] {
				return nil, false
			}
			out[spec.Var] = n
			found = true
			break
		}
		if !found {
			return nil, false
		}
	}
	return out, true
}
